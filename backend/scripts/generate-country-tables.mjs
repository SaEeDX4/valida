#!/usr/bin/env node
/**
 * Generates the two country tables used by a Job's eligible remote-work
 * countries (owner decision OD-2026-11-09-02):
 *
 *   backend/src/modules/jobs/countryCodes.js    the accepted codes (validation)
 *   frontend/src/features/jobs/countryNames.js  code -> English display name
 *
 * from ONE input, so the backend can never accept a code the frontend cannot
 * name, and the frontend can never name a code the backend refuses.
 *
 *   node scripts/generate-country-tables.mjs --iso-codes <path to iso_3166-1.json>
 *
 * Input: iso_3166-1.json from Debian iso-codes (https://salsa.debian.org/iso-codes-team/iso-codes;
 * the committed tables were generated from iso-codes 4.16.0, 249 entries). The
 * code is `alpha_2`; the display name is `common_name` where iso-codes gives one,
 * otherwise `name` (the ISO 3166-1 English short name).
 *
 * The tables are committed; nothing runs this at build or start-up.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..');

const flag = process.argv.indexOf('--iso-codes');
if (flag < 0 || !process.argv[flag + 1]) {
  console.error('Usage: node scripts/generate-country-tables.mjs --iso-codes <path to iso_3166-1.json>');
  process.exit(2);
}
const source = path.resolve(process.argv[flag + 1]);
const versionFlag = process.argv.indexOf('--iso-codes-version');
const version = versionFlag > 0 ? process.argv[versionFlag + 1] : 'unknown';

const entries = JSON.parse(readFileSync(source, 'utf8'))['3166-1'];
const rows = entries
  .map((entry) => ({ code: entry.alpha_2, name: entry.common_name ?? entry.name }))
  .sort((a, b) => a.code.localeCompare(b.code));

const problems = [];
const seen = new Set();
for (const { code, name } of rows) {
  if (!/^[A-Z]{2}$/.test(code)) problems.push(`not two uppercase letters: ${code}`);
  if (seen.has(code)) problems.push(`duplicate code: ${code}`);
  seen.add(code);
  if (typeof name !== 'string' || !name.trim()) problems.push(`no name for ${code}`);
}
if (rows.length < 240) problems.push(`only ${rows.length} entries; expected the full ISO 3166-1 list`);
if (problems.length) {
  console.error(`Refused:\n  - ${problems.join('\n  - ')}`);
  process.exit(1);
}

const provenance = `Debian iso-codes ${version} (iso_3166-1.json, ${rows.length} officially assigned codes)`;

const backend = `/**
 * ISO 3166-1 alpha-2 country codes — the ONE representation of a country in a
 * Job's eligible remote-work countries (\`eligibleWorkCountries\`,
 * OD-2026-11-09-02). Storage, provisioning definitions and the public Job
 * Detail DTO all carry these exact two-letter uppercase codes; nothing else
 * (a name, a lowercase code, an alpha-3 code, a region) is accepted.
 *
 * GENERATED by backend/scripts/generate-country-tables.mjs from
 * ${provenance}.
 * Do not edit by hand. The frontend name table
 * (frontend/src/features/jobs/countryNames.js) is generated from the same
 * input; a frontend test checks that both hold exactly the same codes.
 *
 * Accepting a code says only that it names a country. It does not make that
 * country eligible for anything: only an explicit, approved list on one Job
 * does (Doc 12 / OD-2026-11-09-02).
 */
export const ISO_3166_1_ALPHA_2 = Object.freeze([
${rows.map(({ code }) => `  '${code}',`).join('\n')}
]);

const CODES = new Set(ISO_3166_1_ALPHA_2);

/** True only for an officially assigned ISO 3166-1 alpha-2 code, exactly as written (uppercase). */
export function isIsoCountryCode(value) {
  return typeof value === 'string' && CODES.has(value);
}
`;

const quote = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const frontend = `/**
 * English display names for ISO 3166-1 alpha-2 codes — used to show a Job's
 * eligible remote-work countries (OD-2026-11-09-02) on Job Detail and in its
 * JobPosting \`applicantLocationRequirements\`, so the page and the markup use
 * the same words.
 *
 * GENERATED by backend/scripts/generate-country-tables.mjs from
 * ${provenance}: \`common_name\` where
 * iso-codes gives one, otherwise \`name\`. Do not edit by hand. The backend
 * accepts exactly these codes (backend/src/modules/jobs/countryCodes.js); a
 * test checks that both tables hold the same codes.
 *
 * This is NOT the regional selector's catalogue (markets.js, 21 countries,
 * presentation only), and listing a code here makes nothing eligible.
 */
export const COUNTRY_NAMES = Object.freeze({
${rows.map(({ code, name }) => `  ${code}: ${quote(name)},`).join('\n')}
});

/** The display name of an ISO 3166-1 alpha-2 code, or null for anything else. */
export function countryName(code) {
  return typeof code === 'string' && Object.hasOwn(COUNTRY_NAMES, code) ? COUNTRY_NAMES[code] : null;
}
`;

writeFileSync(path.join(repoRoot, 'backend', 'src', 'modules', 'jobs', 'countryCodes.js'), backend);
writeFileSync(path.join(repoRoot, 'frontend', 'src', 'features', 'jobs', 'countryNames.js'), frontend);
console.log(`wrote ${rows.length} codes from ${provenance}`);
